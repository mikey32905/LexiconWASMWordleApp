        public static bool IsValidGuess(string word)
        {
            if (string.IsNullOrEmpty(word) || word.Length != 5) return false;
            var upper = word.ToUpper();
            return ValidGuesses.Contains(upper) || Array.Exists(Answers, a => a.Equals(upper, StringComparison.OrdinalIgnoreCase));
        }

        public static string GetDailyWord()
        {
            // Use a deterministic seed based on the date
            var epoch = new DateTime(2024, 1, 1);
            var dayNum = (int)(DateTime.Today - epoch).TotalDays;
            var idx = Math.Abs(dayNum) % Answers.Length;
            return Answers[idx].ToUpper();
        }

        public static string GetRandomWord()
        {
            var rng = new Random();
            return Answers[rng.Next(Answers.Length)].ToUpper();
        }
